"""Write requirements.txt for the pipeline: every package pinned by version and by the SHA-256 of
every distribution file PyPI lists for that version, so `pip install --require-hashes` works on any
platform.

Edit PINS (direct and transitive dependencies, each release at least two weeks old) and run:
    python3 -I tools/pipeline/pin_requirements.py
"""

from __future__ import annotations

import json
import urllib.request
from pathlib import Path

# (name, version, environment marker or None)
PINS = (
    ("numpy", "2.5.3", None),
    ("spiceypy", "8.2.0", None),
    ("pytest", "9.1.1", None),
    ("pluggy", "1.6.0", None),
    ("iniconfig", "2.3.0", None),
    ("packaging", "26.3", None),
    ("pygments", "2.21.0", None),
    ("colorama", "0.4.6", 'sys_platform == "win32"'),
)


def main() -> None:
    lines = [
        "# Generated by tools/pipeline/pin_requirements.py. Do not edit by hand.",
        "# Install with: pip install --require-hashes -r tools/pipeline/requirements.txt",
    ]
    for name, version, marker in PINS:
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
            release = json.load(response)
        digests = sorted(f["digests"]["sha256"] for f in release["urls"])
        if not digests:
            raise SystemExit(f"error: PyPI lists no files for {name} {version}")
        requirement = f"{name}=={version}" + (f" ; {marker}" if marker else "")
        lines.append(requirement + " \\")
        lines.extend(f"    --hash=sha256:{d}" + (" \\" if i + 1 < len(digests) else "") for i, d in enumerate(digests))
    out = Path(__file__).with_name("requirements.txt")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()

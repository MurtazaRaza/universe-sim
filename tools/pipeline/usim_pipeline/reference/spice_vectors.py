GENERATED = "Generated by `tools/pipeline/usim-pipeline reference spice`. Do not edit by hand."

# Target and center pairs that need chaining through several segments (in addition to every segment's own pair).
CHAINED_PAIRS = ((399, 0), (301, 0), (301, 399), (399, 10), (199, 399), (5, 10), (299, 301))
# The same for the moons pack: each moon relative to its planet, the planets relative to the Sun, and pairs
# across systems.
MOONS_PACK = "solar-system-moons"
MOONS_CHAINED_PAIRS = (
    (401, 499), (402, 499), (501, 599), (502, 599), (503, 599), (504, 599), (601, 699), (602, 699),
    (603, 699), (604, 699), (605, 699), (606, 699), (608, 699), (701, 799), (702, 799), (703, 799),
    (704, 799), (705, 799), (801, 899), (901, 999), (499, 10), (599, 10), (699, 10), (799, 10), (899, 10),
    (999, 10), (599, 399), (606, 399), (501, 503), (901, 801), (401, 301),
)  # fmt: skip
MOON_RECORD_STEPS = (1, 2, 1000)  # record boundaries of each segment pair, counted from its first record
RANDOM_EPOCHS_PER_PAIR = 40
RECORD_BOUNDARY_STEPS = (1, 2, 1000, 17123, 34000, 34249)  # multiples of 32 d, which every record grid contains
COMMON_GRID_S = 32 * 86400.0
ORIENTATION_EPOCHS_PER_BODY = 30
UTC_RANDOM_EPOCHS = 100
TDB_RANDOM_EPOCHS = 100


def _header(title: str, entries: list[LockEntry], details: list[str]) -> list[str]:
    return [title, GENERATED, f"Tools: {tool_line()}", "Kernels:", *(f"  {line}" for line in kernel_lines(entries)), *details]


def _span(segments) -> tuple[float, float]:
    return max(s.start_s for s in segments), min(s.end_s for s in segments)


def _state_rows(segments, pairs: list[tuple[int, int]]) -> Iterator[list[str]]:
    start, end = _span(segments)
    init = min(s.init_s for s in segments)
    for target, center in pairs:
        rng = random.Random(target * 1_000_003 + center)
        epochs = [start, end, 0.0]
        epochs += [init + k * COMMON_GRID_S for k in RECORD_BOUNDARY_STEPS if init + k * COMMON_GRID_S < end]
        epochs += [start + rng.random() * (end - start) for _ in range(RANDOM_EPOCHS_PER_PAIR)]
        for et in epochs:
            state, _ = sp.spkgeo(target, et, "J2000", center)
            yield [str(target), str(center), exact(et), *(exact(v) for v in state)]


def write_states(path: Path, segments, entries: list[LockEntry]) -> int:
    pairs = [(s.target, s.center) for s in segments]
    pairs += [p for p in CHAINED_PAIRS if p not in pairs]
    start, end = _span(segments)
    header = _header(
        "VAL-01 reference: geometric states from CSPICE spkgeo on the same DE440 kernel the pack is built from.",
        entries,
        [
            "Query: spkgeo(target, et, 'J2000', center): no light time or aberration correction.",
            "Columns: NAIF IDs; TDB seconds past J2000; position (km) and velocity (km/s) in the ICRF (SPICE J2000).",
            f"Epochs: coverage start and end ({exact(start)}, {exact(end)}), J2000, record boundaries, and "
            f"{RANDOM_EPOCHS_PER_PAIR} seeded random epochs per pair.",
            "Pairs: every segment's own target and center, plus pairs that chain through several segments.",
        ],
    )
    columns = ["target", "center", "tdb_s", "x_km", "y_km", "z_km", "vx_km_s", "vy_km_s", "vz_km_s"]
    return write_csv(path, header, columns, _state_rows(segments, pairs))


def _moon_state_rows(segments, pairs: list[tuple[int, int]], span: tuple[float, float]) -> Iterator[list[str]]:
    start, end = span
    by_pair: dict[tuple[int, int], list] = {}
    for s in segments:
        by_pair.setdefault((s.target, s.center), []).append(s)
    for target, center in pairs:
        rng = random.Random(target * 1_000_003 + center + 77)
        epochs = [start, end]
        for s in by_pair.get((target, center), []):
            epochs += [s.init_s + k * s.interval_s for k in MOON_RECORD_STEPS if k < s.record_count]
        epochs = [e for e in epochs if start <= e <= end]
        epochs += [start + rng.random() * (end - start) for _ in range(RANDOM_EPOCHS_PER_PAIR)]
        for et in epochs:
            state, _ = sp.spkgeo(target, et, "J2000", center)
            yield [str(target), str(center), exact(et), *(exact(v) for v in state)]


def write_moon_states(path: Path, segments, span: tuple[float, float], entries: list[LockEntry]) -> int:
    pairs = sorted({(s.target, s.center) for s in segments})
    pairs += [p for p in MOONS_CHAINED_PAIRS if p not in pairs]
    header = _header(
        f"VAL-01 reference for the optional pack '{MOONS_PACK}': geometric states from CSPICE spkgeo on the "
        "kernels it is built from.",
        entries,
        [
            "Kernels are loaded satellite kernels first and de440s.bsp last, so DE440 supplies the planetary",
            "segments (as in the pack, which takes only the segments relative to each system barycenter from",
            "the satellite kernels).",
            "Query: spkgeo(target, et, 'J2000', center): no light time or aberration correction.",
            "Columns: NAIF IDs; TDB seconds past J2000; position (km) and velocity (km/s) in the ICRF (SPICE J2000).",
            f"Epochs: the pack window ({exact(span[0])}, {exact(span[1])}), record boundaries of each segment "
            f"pair, and {RANDOM_EPOCHS_PER_PAIR} seeded random epochs per pair.",
            "Pairs: every segment's own target and center, each moon relative to its planet, the planets",
            "relative to the Sun, and pairs across systems.",
        ],
    )
    columns = ["target", "center", "tdb_s", "x_km", "y_km", "z_km", "vx_km_s", "vy_km_s", "vz_km_s"]
    return write_csv(path, header, columns, _moon_state_rows(segments, pairs, span))


def _utc_cases(leap_dates: list[tuple[int, int, int]]) -> list[str]:
    """UTC epochs with binary-fraction seconds (CSPICE parses decimal fractions inexactly; see unit_fixtures)."""
    cases = []
    first = datetime.date(*leap_dates[0])
    cases.append(f"{first.isoformat()}T00:00:00")
    for year, month, day in leap_dates[1:]:
        before = datetime.date(year, month, day) - datetime.timedelta(days=1)
        cases += [f"{before.isoformat()}T23:59:59.5", f"{before.isoformat()}T23:59:60.25", f"{year:04d}-{month:02d}-{day:02d}T00:00:00"]
    rng = random.Random(3)
    last = datetime.date(2150, 1, 1)
    for _ in range(UTC_RANDOM_EPOCHS):
        day = first + datetime.timedelta(days=rng.randrange((last - first).days))
        second = rng.randrange(86400)
        fraction = rng.randrange(64) / 64  # at most 6 decimal digits, exact in binary
        cases.append(
            f"{day.isoformat()}T{second // 3600:02d}:{second // 60 % 60:02d}:{second % 60 + fraction:09.6f}"
        )
    return cases


def write_time(directory: Path, lsk_entry: LockEntry, leap_dates: list[tuple[int, int, int]], span: tuple[float, float]) -> int:
    sp.timdef("SET", "CALENDAR", 10, "GREGORIAN")
    header = _header(
        "VAL-03 reference: UTC -> TDB from CSPICE str2et, and back with et2utc (ISOC, 6 decimals).",
        [lsk_entry],
        [
            "Columns: UTC (ISO 8601, Gregorian, no suffix); TDB seconds past J2000; et2utc of that value.",
            "Epochs: around every leap second in the table, and seeded random epochs from the table start to 2150.",
            "Fractions of a second are binary fractions: CSPICE's UTC parser rounds decimal fractions with errors up",
            "to 1.7e-9 s (measured 2026-10-20, IMPLEMENTATION_PLAN P1-04).",
        ],
    )
    rows = []
    for utc in _utc_cases(leap_dates):
        et = sp.str2et(utc)
        rows.append([utc, exact(et), sp.et2utc(et, "ISOC", 6)])
    count = write_csv(directory / "val03_utc_to_tdb.csv", header, ["utc", "tdb_s", "utc_isoc6"], rows)

    header = _header(
        "VAL-03 reference: TDB <-> TT <-> TAI from CSPICE unitim.",
        [lsk_entry],
        [
            "Columns: TDB, TT (SPICE TDT) and TAI seconds past J2000 at the same instant, and unitim(TT -> TDB).",
            "Epochs: J2000 and seeded random epochs across the coverage of the default pack's ephemeris.",
        ],
    )
    rng = random.Random(4)
    epochs = [0.0] + [span[0] + rng.random() * (span[1] - span[0]) for _ in range(TDB_RANDOM_EPOCHS)]
    rows = []
    for et in epochs:
        tt = sp.unitim(et, "TDB", "TDT")
        rows.append([exact(et), exact(tt), exact(sp.unitim(et, "TDB", "TAI")), exact(sp.unitim(tt, "TDT", "TDB"))])
    count += write_csv(directory / "val03_tdb_tt_tai.csv", header, ["tdb_s", "tt_s", "tai_s", "tdb_from_tt_s"], rows)
    return count


def write_orientation(
    path: Path, bodies: list[int], span: tuple[float, float], entries: list[LockEntry], scope: str = ""
) -> int:
    header = _header(
        "VAL-04 reference: body orientation from CSPICE pxform and sxform with the same PCK the pack is built from."
        + scope,
        entries,
        [
            "Query: sxform('J2000', frame, et) for the body's IAU frame (cidfrm). R rotates ICRF vectors into the",
            "body-fixed frame; dR is its time derivative (per TDB second), the lower left block of the 6x6 matrix.",
            "Matrices are row-major: r01 is row 0, column 1.",
            f"Epochs: J2000 and {ORIENTATION_EPOCHS_PER_BODY} seeded random epochs per body across the pack coverage.",
            "CSPICE reads some PCK values one ulp away from the correctly rounded text the pack holds (ADR-0007);",
            "the effect on orientation is far below the VAL-04 threshold.",
        ],
    )
    columns = ["body", "frame", "tdb_s", *(f"r{i}{j}" for i in range(3) for j in range(3)), *(f"dr{i}{j}" for i in range(3) for j in range(3))]

    def rows() -> Iterator[list[str]]:
        for body in bodies:
            _, frame = sp.cidfrm(body)
            rng = random.Random(10_000 + body)
            for et in [0.0] + [span[0] + rng.random() * (span[1] - span[0]) for _ in range(ORIENTATION_EPOCHS_PER_BODY)]:
                m = sp.sxform("J2000", frame, et)
                rotation = [exact(m[i][j]) for i in range(3) for j in range(3)]
                rate = [exact(m[3 + i][j]) for i in range(3) for j in range(3)]
                yield [str(body), frame, exact(et), *rotation, *rate]

    return write_csv(path, header, columns, rows())


def write_kernel_values(path: Path, definition: PackDefinition, selection_ids: list[int], files: dict[str, tuple[Path, LockEntry]]) -> int:
    """Every numeric variable of the default pack's text kernels that concerns its bodies, as written in the
    files. The core's validation test parses the text itself and compares with the pack (exact match)."""
    owners = sorted(set(selection_ids) | {system_barycenter(i) for i in selection_ids})
    header = _header(
        "Pack check: numeric values of the text kernels, exactly as written in the files.",
        [entry for _, entry in files.values()],
        [
            f"Scope: BODY<n>_* variables for the bodies of pack '{definition.name}' and their system barycenters,",
            "and DELTET/* of the leap seconds kernel. Each value was cross-checked against CSPICE's kernel pool.",
            "Columns: file name; variable; index of the value within the variable; the value's text as written.",
            "@-dates are written as in the kernel (for example @1972-JAN-1).",
        ],
    )

    def rows() -> Iterator[list[str]]:
        for name in sorted(files):
            kernel_path, _ = files[name]
            reader = KernelReader(kernel_path)
            with kernel_pool(kernel_path):
                for variable in sorted(reader.kernel.variables):
                    wanted = variable.startswith("DELTET/") or any(variable.startswith(f"BODY{n}_") for n in owners)
                    tokens = reader.kernel.text(variable) or []
                    if not wanted or any(t.startswith("'") for t in tokens):
                        continue
                    reader.numbers(variable)  # cross-check with CSPICE
                    for index, token in enumerate(tokens):
                        yield [name, variable, str(index), token]

    return write_csv(path, header, ["file", "variable", "index", "text"], rows())


def generate(repo: Repo, log: Callable[[str], None] = print) -> list[Path]:
    check_environment()
    sources: tuple[Source, ...] = load_sources(repo.sources_file)
    definition = next(d for d in load_pack_definitions(repo.catalog / "packs.json") if d.name == "solar-system")
    refs = [*definition.ephemeris, definition.shape_and_rotation, definition.gm, definition.time]
    files = {ref.file: locked_file(repo, sources, ref.source_id, ref.file) for ref in refs}
    spk_path, spk_entry = files[definition.ephemeris[0].file]
    pck_path, pck_entry = files[definition.shape_and_rotation.file]
    lsk_path, lsk_entry = files[definition.time.file]
    selection = load_selection(repo.catalog / definition.bodies)
    out = repo.reference
    written = []

    segments = read_spk_segments(spk_path)  # before the pool loads the file, so DAF handles are not shared
    span = _span(segments)
    with kernel_pool(spk_path, lsk_path):
        count = write_states(out / "val01_spk_states.csv", segments, [spk_entry])
        written.append(out / "val01_spk_states.csv")
        log(f"wrote {written[-1]} ({count} states)")
        tokens = KernelReader(lsk_path).kernel.text("DELTET/DELTA_AT") or []
        leap_dates = [parse_at_date(t) for t in tokens if t.startswith("@")]
        count = write_time(out, lsk_entry, leap_dates, span)
        written += [out / "val03_utc_to_tdb.csv", out / "val03_tdb_tt_tai.csv"]
        log(f"wrote {written[-2]} and {written[-1]} ({count} rows)")

    with kernel_pool(pck_path, lsk_path):
        with_rotation = []
        pck_reader = KernelReader(pck_path)
        for s in selection:
            if pck_reader.kernel.text(f"BODY{s.naif_id}_PM") is not None:
                with_rotation.append(s.naif_id)
        count = write_orientation(out / "val04_orientation.csv", with_rotation, span, [pck_entry])
        written.append(out / "val04_orientation.csv")
        log(f"wrote {written[-1]} ({count} orientations)")

    text_files = {ref.file: files[ref.file] for ref in (definition.shape_and_rotation, definition.gm, definition.time)}
    count = write_kernel_values(out / "pack_kernel_values.csv", definition, [s.naif_id for s in selection], text_files)
    written.append(out / "pack_kernel_values.csv")
    log(f"wrote {written[-1]} ({count} values)")

    moons = next((d for d in load_pack_definitions(repo.catalog / "packs.json") if d.name == MOONS_PACK), None)
    if moons is not None:
        try:
            written += _moons_pack_references(repo, moons, sources, [s.naif_id for s in selection], log)
        except PipelineError as error:
            log(f"skipped the {MOONS_PACK} references: {error}")
    return written


def _moons_pack_references(
    repo: Repo, definition: PackDefinition, sources: tuple[Source, ...], default_bodies: list[int],
    log: Callable[[str], None],
) -> list[Path]:
    """VAL-01 and VAL-04 vectors for the optional moons pack. Fails (and is skipped by the caller) when its
    satellite kernels have not been downloaded."""
    if definition.window is None:
        raise PipelineError(f"{definition.name} has no window")
    ephemeris = [(ref, *locked_file(repo, sources, ref.source_id, ref.file)) for ref in definition.ephemeris]
    pck_path, pck_entry = locked_file(repo, sources, definition.shape_and_rotation.source_id, definition.shape_and_rotation.file)
    lsk_path, _ = locked_file(repo, sources, definition.time.source_id, definition.time.file)
    selection = load_selection(repo.catalog / definition.bodies)
    selected = {s.naif_id for s in selection}
    segments = []
    for ref, path, _ in ephemeris:
        def keep(target: int, center: int, centers: tuple[int, ...] | None = ref.centers) -> bool:
            return target in selected and (centers is None or center in centers)

        segments += read_spk_segments(path, keep, definition.window)
    span = definition.window
    out = repo.reference
    written = []
    # Satellite kernels first, de440s.bsp (the planetary ephemeris, no center filter) last: later files win.
    planetary = [path for ref, path, _ in ephemeris if ref.centers is None]
    satellites = [path for ref, path, _ in ephemeris if ref.centers is not None]
    with kernel_pool(*satellites, *planetary, lsk_path):
        path = out / "val01_moons_spk_states.csv"
        count = write_moon_states(path, segments, span, [entry for _, _, entry in ephemeris])
        written.append(path)
        log(f"wrote {path} ({count} states)")

    with kernel_pool(pck_path, lsk_path):
        pck_reader = KernelReader(pck_path)
        bodies = [s.naif_id for s in selection
                  if s.naif_id not in default_bodies and pck_reader.kernel.text(f"BODY{s.naif_id}_PM") is not None]
        path = out / "val04_moons_orientation.csv"
        count = write_orientation(path, bodies, span, [pck_entry],
                                  f" Bodies of the optional pack '{MOONS_PACK}' that the default pack does not have.")
        written.append(path)
        log(f"wrote {path} ({count} orientations)")
    return written
